#!/usr/bin/env python3
"""Build the data files of the YBh corpus map.

Two layers are combined:

1. ``data/delhey.json`` -- hand-curated, bibliographic layer. Every span is a
   claim made by Martin Delhey (2013), with the page of his article. Spans are
   given in the coordinates Delhey uses: Taishō (``t``), a named section of
   T1579 (``sec``), pages of Bhattacharya 1957 (``bh``), Shukla 1973 (``sh``),
   Dutt 1966 (``bobhd``) or Peking folios (``q``).
2. ``data/derived.json`` -- data-derived layer, regenerated by this script from
   the DharmaNexus segment files and the multilingual sentence alignments
   (Sanskrit<->Chinese, Tibetan<->Chinese). It contains the stretches of T1579
   to which each DharmaNexus e-text is aligned, and page concordances
   (Bh./Sh./BoBhD -> Taishō) used to place Delhey's edition-page spans.

``data/corpus.json`` (and ``data/corpus.js`` for offline use from file://) is
the merged result that ``index.html`` displays.

Usage
-----
Full rebuild (needs the DharmaNexus data and the alignment releases)::

    python3 scripts/build_data.py \
        --sanskrit PATH/dharmanexus-sanskrit/segments \
        --sanskrit-old-n1394u PATH/old_SA_T06_n1394u.json \
        --matches  PATH/mitra-parallel-v3 [--matches PATH/other-release ...]

Merge only (re-resolve ``delhey.json`` with the committed ``derived.json``)::

    python3 scripts/build_data.py --merge-only

Only the Python standard library is used.
"""
import argparse
import bisect
import difflib
import glob
import gzip
import json
import os
import re
import statistics
import sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")

T_START, T_END = 279, 882          # T1579 occupies Taishō vol. 30, pp. 279a-882a
LINES = 29                          # nominal lines per register (lines > 29 are clamped)

# ---------------------------------------------------------------- Taishō axis
TPOS = re.compile(r"^0?(\d{3})([abc])(\d{1,2})?$")


def t2x(s, end=False):
    """'0328c07' / '328c7' / '328c' -> position in registers from 279a1."""
    m = TPOS.match(s.strip())
    if not m:
        raise ValueError("bad Taishō position %r" % s)
    page, reg, line = int(m.group(1)), "abc".index(m.group(2)), m.group(3)
    if line is None:                # register only: whole register
        frac = 1.0 if end else 0.0
    else:
        frac = (min(int(line), LINES) - (0 if end else 1)) / LINES
    return round((page - T_START) * 3 + reg + frac, 4)


def x2t(x):
    x = max(0.0, x)
    page = int(x // 3) + T_START
    reg = int(x % 3)
    line = int(round((x - (page - T_START) * 3 - reg) * LINES)) + 1
    if line > LINES:
        line = LINES
    return "%d%s%d" % (page, "abc"[reg], line)


def seg_t(segnr):
    """'ZH_T30_1579_011:0328c07_8' -> x."""
    return t2x(segnr.split(":")[1].split("_")[0])


# ------------------------------------------------------------- alignments
YBH_ZH = {"ZH_T30_1579", "ZH_T30_1581", "ZH_T30_1582", "ZH_T24_1500", "ZH_T24_1501"}
YBH_SA = {
    "SA_T06_n1394u", "SA_T06_sambhu", "SA_T06_-ybh-klesa", "SA_T06_srabhusu",
    "SA_T06_srabhu_u", "SA_T06_ybh-laukikamarga", "SA_T06_bsa034",
    "SA_T06_abhsubhu", "SA_T06_asycsaru", "SA_T06_Asaṅga_Bodhisattvabhūmi",
    "SA_T06_Asaṅga_Bodhisattvabhūmi-wogiwara", "SA_K01_bsu011_u",
}
YBH_BO = re.compile(r"^BO_T06_D40(3[5-9]|4[0-7])")


def text_of(segnr):
    head = segnr.split(":")[0]
    if head.startswith("ZH_"):
        return head.rsplit("_", 1)[0]
    return head


def iter_matches(dirs, name):
    """Yield records from <dir>/<name>; later dirs override earlier ones per file."""
    for d in dirs:
        p = os.path.join(d, name)
        if not os.path.exists(p):
            continue
        with gzip.open(p, "rt", encoding="utf-8") as fh:
            for line in fh:
                if "ZH_T30_15" not in line and "ZH_T24_150" not in line:
                    continue
                yield d, json.loads(line)


def load_alignments(dirs):
    """Return {source_file: [(root_segnrs, zh_segnrs, release)]} for YBh texts."""
    out = defaultdict(list)
    newest = {}                              # file -> index of newest release seen
    for i, d in enumerate(dirs):
        for name in ("sa-zh_matches.ndjson.gz", "bo-zh_matches.ndjson.gz"):
            p = os.path.join(d, name)
            if not os.path.exists(p):
                continue
            seen = set()
            for _, r in iter_matches([d], name):
                src = r["filename"] if "filename" in r else text_of(r["root_segnr"][0])
                src = text_of(r["root_segnr"][0])
                zh = [p_ for p_ in r["par_segnr"] if text_of(p_) in YBH_ZH]
                if not zh:
                    continue
                if not (src in YBH_SA or YBH_BO.match(src)):
                    continue
                seen.add(src)
                out[(src, i)].append((r["root_segnr"], zh))
            for s in seen:
                newest[s] = max(newest.get(s, -1), i)
    res = {}
    for (src, i), recs in out.items():
        if newest[src] == i:
            res[src] = {"release": os.path.basename(os.path.normpath(dirs[i])), "records": recs}
    return res


# ------------------------------------------------------------ segment files
def load_json(p):
    with open(p, encoding="utf-8") as fh:
        return json.load(fh)


def sa_segments(sa_dir, fid):
    p = os.path.join(sa_dir, fid + ".json")
    return load_json(p) if os.path.exists(p) else None


def page_markers(segs, rx):
    """Map segment index -> edition page (or folio) current at its start."""
    conv = lambda v: int(v) if v.isdigit() else v
    pages, cur = {}, None
    for i, s in enumerate(segs):
        ms = list(rx.finditer(s["original"]))
        if ms and ms[0].start() < 3:          # marker at the very beginning
            cur = conv(ms[0].group(1))
        pages[i] = cur
        if ms:
            cur = conv(ms[-1].group(1))
    return pages


def norm(s):
    return re.sub(r"[^a-zāīūṛṝḷṃṅñṭḍṇśṣḥ]", "", s.lower())


def old_to_new(old_segs, new_segs):
    """Map old segment index -> new segment index by aligning texts."""
    a = [norm(s["original"]) for s in old_segs]
    b = [norm(s["original"]) for s in new_segs]
    sm = difflib.SequenceMatcher(None, a, b, autojunk=False)
    mp = {}
    for blk in sm.get_matching_blocks():
        for k in range(blk.size):
            mp[blk.a + k] = blk.b + k
    # fill gaps by interpolation between matched neighbours
    keys = sorted(mp)
    for i in range(len(a)):
        if i in mp:
            continue
        j = bisect.bisect_left(keys, i)
        lo = keys[j - 1] if j > 0 else None
        hi = keys[j] if j < len(keys) else None
        if lo is not None and hi is not None:
            mp[i] = mp[lo] + round((i - lo) * (mp[hi] - mp[lo]) / (hi - lo))
        elif lo is not None:
            mp[i] = mp[lo]
        elif hi is not None:
            mp[i] = mp[hi]
    return mp


# ----------------------------------------------------------- span building
def runs(points, gap=1.5, min_n=4):
    """Cluster sorted T positions into runs; drop runs with < min_n points."""
    pts = sorted(points)
    out, cur = [], []
    for p in pts:
        if cur and p - cur[-1] > gap:
            out.append(cur)
            cur = []
        cur.append(p)
    if cur:
        out.append(cur)
    return [(r[0], r[-1], len(r)) for r in out if len(r) >= min_n]


def concordance(pairs):
    """pairs [(own_page, x)] -> monotone list [(page, x_median)]."""
    by = defaultdict(list)
    for pg, x in pairs:
        if pg is not None:
            by[pg].append(x)
    pts = sorted((pg, statistics.median(v)) for pg, v in by.items() if len(v) >= 2)
    # enforce monotonicity: drop points that go backwards vs. the running median
    clean = []
    for pg, x in pts:
        window = [c[1] for c in clean[-5:]]
        if window and x < statistics.median(window) - 3:
            continue
        clean.append((pg, round(x, 3)))
    return clean



def page_label_fn(fid, segs, args):
    """Return f(segment index) -> (label, page) giving the edition page."""
    if segs is None:
        return None
    if fid == "SA_T06_n1394u":
        # the alignments refer to the old DSBC segmentation; map them to the new
        # e-text whose `folio` is the page of Bhattacharya 1957
        old = load_json(args.sanskrit_old_n1394u) if args.sanskrit_old_n1394u else None
        mp = old_to_new(old, segs) if old is not None else {i: i for i in range(len(segs))}
        return lambda i: ("Bh.", segs[min(mp.get(i, i), len(segs) - 1)]["folio"])
    rx = {"SA_T06_srabhusu": (r"\(Śbh_Sh:? (\d+)\)", "Sh."),
          "SA_T06_bsa034": (r"\(Dutt (\d+)\)", "BoBhD"),
          "SA_T06_ybh-laukikamarga": (r"\(Sh (\d+), \d+\)", "Sh."),
          "SA_T06_sambhu": (r"\bH (\d+[ab]\d)", "YoBh MS"),
          "SA_T06_srabhu_u": (r"\((Śbh I{1,2} \d+)\)", "")}.get(fid)
    if not rx:
        return lambda i: ("seg.", i)
    pg = page_markers(segs, re.compile(rx[0]))
    lab = rx[1]
    return lambda i: (lab, pg.get(i))


def wogihara_label_fn(segs):
    def f(i):
        m = re.match(r"^\s*(\d+)/(\d+)/", segs[i]["original"])
        return ("BoBhW", int(m.group(1))) if m else ("BoBhW", None)
    return f


def grams(s, n=6):
    s = norm(s)
    return {s[k:k + n] for k in range(0, max(0, len(s) - n + 1))}


def match_to_aligned(segs, ref, ref2t):
    """Locate each segment of an unaligned e-text in an aligned reference e-text
    (same work, other edition) by shared character 6-grams; return points
    (x, segment index) and (Wogihara page, x) pairs."""
    index = defaultdict(set)
    for j, s in enumerate(ref):
        for g in grams(s["original"]):
            index[g].add(j)
    aligned = sorted(ref2t)
    pts, wpairs = [], []
    for i, s in enumerate(segs):
        txt = re.sub(r"^\s*\d+/\d+/\.?", "", s["original"])
        gs = grams(txt)
        if len(gs) < 8:
            continue
        score = defaultdict(int)
        for g in gs:
            js = index.get(g)
            if js and len(js) < 30:
                for j in js:
                    score[j] += 1
        if not score:
            continue
        j, sc = max(score.items(), key=lambda kv: kv[1])
        if sc < 0.4 * len(gs):
            continue
        k = bisect.bisect_left(aligned, j)
        cand = [aligned[c] for c in (k - 1, k) if 0 <= c < len(aligned)]
        if not cand:
            continue
        jj = min(cand, key=lambda c: abs(c - j))
        if abs(jj - j) > 3:
            continue
        x = statistics.median(ref2t[jj])
        pts.append((x, i))
        m = re.match(r"^\s*(\d+)/(\d+)/", s["original"])
        if m:
            wpairs.append((int(m.group(1)), x))
    return pts, wpairs


def make_entry(release, n_al, pts, label, order="idx"):
    """Group aligned points (x, own index) into runs on the T1579 axis."""
    entry = {"release": release, "n_alignments": n_al, "spans": []}
    pts = sorted(pts)
    xs = [p[0] for p in pts]
    for a, b, n in runs(xs):
        sp = {"from": x2t(a), "to": x2t(b + 1 / LINES), "x0": a, "x1": round(b + 1 / LINES, 4), "n": n}
        if label:
            lo, hi = bisect.bisect_left(xs, a), bisect.bisect_right(xs, b)
            own = [p[1] for p in pts[lo:hi]]
            if order == "idx":
                own.sort()
            trim = len(own) // 50
            i0, i1 = own[trim], own[len(own) - 1 - trim]
            l0, l1 = label(i0), label(i1)
            if l0[1] is not None and l1[1] is not None:
                sp["own"] = ("%s %s–%s" % (l0[0], l0[1], l1[1])).strip()
        entry["spans"].append(sp)
    return entry


def build_derived(args):
    dirs = args.matches
    al = load_alignments(dirs)
    sys.stderr.write("aligned files: %s\n" % sorted(al))
    derived = {"releases": [os.path.basename(os.path.normpath(d)) for d in dirs],
               "etexts": {}, "concordances": {}}

    # page / own-label functions for Sanskrit e-texts
    labels = {}
    conc_pairs = defaultdict(list)

    sa2t = {}            # Sanskrit e-text -> {segment index: [x, ...]}
    for fid in sorted(al):
        recs = al[fid]["records"]
        if fid.startswith("SA_"):
            segs = sa_segments(args.sanskrit, fid)
            label = page_label_fn(fid, segs, args)
            pts = []                       # (x, segment index)
            m = defaultdict(list)
            for root, zh in recs:
                for z in zh:
                    if text_of(z) != "ZH_T30_1579":
                        continue
                    x = seg_t(z)
                    for r_ in root:
                        i = int(r_.split(":")[1])
                        pts.append((x, i))
                        m[i].append(x)
            sa2t[fid] = m
            if label:
                for x, i in pts:
                    lab, pg = label(i)
                    if isinstance(pg, int):
                        conc_pairs[lab].append((pg, x))
            derived["etexts"][fid] = make_entry(al[fid]["release"], len(recs), pts, label)
        else:  # Tibetan: own pagination = Derge folio of the segment
            pts, fol = [], {}
            for root, zh in recs:
                for z in zh:
                    if text_of(z) != "ZH_T30_1579":
                        continue
                    k = len(fol)
                    fol[k] = root[0].split(":")[1].split("-")[0]
                    pts.append((seg_t(z), k))
            derived["etexts"][fid] = make_entry(
                al[fid]["release"], len(recs), pts, lambda k, fol=fol: ("D fol.", fol[k]), order="x")

    # Wogihara e-texts (not aligned): match their lines to the aligned Dutt e-text
    if "SA_T06_bsa034" in sa2t:
        dutt = sa_segments(args.sanskrit, "SA_T06_bsa034")
        for fid in ("SA_T06_Asaṅga_Bodhisattvabhūmi", "SA_T06_Asaṅga_Bodhisattvabhūmi-wogiwara"):
            segs = sa_segments(args.sanskrit, fid)
            if not segs:
                continue
            pts, wpairs = match_to_aligned(segs, dutt, sa2t["SA_T06_bsa034"])
            if fid == "SA_T06_Asaṅga_Bodhisattvabhūmi":
                conc_pairs["BoBhW"].extend(wpairs)
            lab = wogihara_label_fn(segs)
            e = make_entry("text match to SA_T06_bsa034", 0, pts, lab)
            e["via"] = "SA_T06_bsa034"
            derived["etexts"][fid] = e

    # Chinese partial BoBh translations, chained via the Sanskrit BoBh (bsa034)
    if "SA_T06_bsa034" in al:
        bs2t = defaultdict(list)
        sa2other = defaultdict(lambda: defaultdict(list))
        for root, zh in al["SA_T06_bsa034"]["records"]:
            for z in zh:
                t = text_of(z)
                for r_ in root:
                    if t == "ZH_T30_1579":
                        bs2t[r_].append(seg_t(z))
                    else:
                        sa2other[t][r_].append(z.split(":")[1].split("_")[0])
        for t, mp in sa2other.items():
            pts, own = [], []
            for r_, locs in mp.items():
                if r_ in bs2t:
                    for x in bs2t[r_]:
                        pts.append(x)
                        own.append((x, locs[0]))
            own.sort()
            xs = [o[0] for o in own]
            entry = {"release": al["SA_T06_bsa034"]["release"], "via": "SA_T06_bsa034",
                     "n_alignments": len(pts), "spans": []}
            for a, b, n in runs(pts, gap=3, min_n=4):
                sp = {"from": x2t(a), "to": x2t(b + 1 / LINES), "x0": a, "x1": round(b + 1 / LINES, 4), "n": n}
                lo = bisect.bisect_left(xs, a)
                hi = bisect.bisect_right(xs, b) - 1
                if 0 <= lo <= hi:
                    locs = sorted(o[1] for o in own[lo:hi + 1])
                    sp["own"] = "%s %s–%s" % (t.replace("ZH_", "").replace("_", "."), locs[0], locs[-1])
                entry["spans"].append(sp)
            derived["etexts"][t] = entry

    for lab, pairs in conc_pairs.items():
        derived["concordances"][lab] = concordance(pairs)
    return derived


# ---------------------------------------------------------------- merging
def interp(conc, page, line=None, lines_per_page=24):
    """Edition page(,line) -> x by linear interpolation in a concordance."""
    pos = page + ((line - 1) / lines_per_page if line else 0.0)
    pg = [c[0] for c in conc]
    xs = [c[1] for c in conc]
    if not pg:
        raise ValueError("empty concordance")
    if pos <= pg[0]:
        return xs[0]
    if pos >= pg[-1]:
        return xs[-1]
    j = bisect.bisect_right(pg, pos)
    p0, p1, x0, x1 = pg[j - 1], pg[j], xs[j - 1], xs[j]
    return x0 + (pos - p0) * (x1 - x0) / (p1 - p0)


def parse_pl(s):
    """'160,10' -> (160, 10); '137' -> (137, None)."""
    if "," in s:
        a, b = s.split(",")
        return int(a), int(b)
    return int(s), None


def qnum(f):
    """Peking folio ["zi"|"'i"]'300a7' -> continuous number (8 lines per side)."""
    m = re.match(r"^(zi|'i)?(\d+)([ab])(\d)?$", f)
    vol, n, side, line = m.group(1), int(m.group(2)), m.group(3), int(m.group(4) or 1)
    return (1000 if vol == "'i" else 0) + n * 2 + (0 if side == "a" else 1) + (line - 1) / 8


def resolve(span, sections, derived, qanchors):
    """Add x0/x1 and the basis of placement to a curated span."""
    conc = derived.get("concordances", {})
    if "t" in span:
        a, b = span["t"]
        span["x0"], span["x1"] = t2x(a), t2x(b, end=True)
        span["basis"] = "delhey-T"
    elif "sec" in span:
        secs = span["sec"] if isinstance(span["sec"], list) else [span["sec"]]
        span["x0"] = min(sections[s]["x0"] for s in secs)
        span["x1"] = max(sections[s]["x1"] for s in secs)
        span["basis"] = "section"
    elif any(k in span for k in ("bh", "sh", "bobhd")):
        key, lab, lpp = (("bh", "Bh.", 22) if "bh" in span else
                         ("sh", "Sh.", 20) if "sh" in span else ("bobhd", "BoBhD", 26))
        c = conc.get(lab)
        if not c:
            raise ValueError("no concordance for %s" % lab)
        a, b = span[key]
        pa, la = parse_pl(a)
        pb, lb = parse_pl(b)
        x0 = interp(c, pa, la, lpp)
        x1 = interp(c, pb + (0 if lb else 1), lb, lpp)
        if x1 < x0:
            x0, x1 = x1, x0
        span["x0"], span["x1"] = round(x0, 3), round(max(x1, x0 + 0.15), 3)
        span["basis"] = "concordance"
    elif "q" in span:
        q = span["q"]
        anc = qanchors[q["text"]]
        pts = sorted((qnum(f), t2x(t)) for f, t in anc)
        def qx(f):
            v = qnum(f)
            ks = [p[0] for p in pts]
            j = bisect.bisect_right(ks, v)
            j = min(max(j, 1), len(pts) - 1)
            (k0, x0), (k1, x1) = pts[j - 1], pts[j]
            return x0 + (v - k0) * (x1 - x0) / (k1 - k0)
        span["x0"], span["x1"] = round(qx(q["from"]), 3), round(qx(q["to"]), 3)
        span["basis"] = "q-interpolated"
    else:
        raise ValueError("span without coordinates: %r" % span)
    span["from"], span["to"] = x2t(span["x0"]), x2t(max(span["x0"], span["x1"] - 1 / LINES))
    return span


def merge(curated, derived):
    sections = {}
    for s in curated["sections"]:
        s["x0"], s["x1"] = t2x(s["from"]), t2x(s["to"])
        sections[s["id"]] = s
    qanchors = curated.get("q_anchors", {})
    # fixed anchors (e.g. first page of an edition = start of its section)
    for lab, pts in curated.get("concordance_anchors", {}).items():
        c = derived.setdefault("concordances", {}).setdefault(lab, [])
        for pg, t in pts:
            c[:] = sorted([q for q in c if q[0] != pg] + [[pg, t2x(t)]])
    for row in curated["rows"]:
        for sp in row.get("spans", []):
            resolve(sp, sections, derived, qanchors)
    # data-derived rows
    drows = []
    for spec in curated.get("derived_rows", []):
        spec = dict(spec)
        e = derived["etexts"].get(spec["etext"])
        if not e:
            continue
        r = dict(spec)
        r["spans"] = [dict(s, basis="aligned") for s in e["spans"]]
        r["release"] = e.get("release")
        r["n_alignments"] = e.get("n_alignments")
        drows.append(r)
    out = {
        "title": curated["title"],
        "axis": curated["axis"],
        "groups": curated["groups"],
        "sections": curated["sections"],
        "rows": curated["rows"] + drows,
        "sources": curated["sources"],
        "derived_info": {"releases": derived.get("releases"),
                         "concordances": {k: len(v) for k, v in derived.get("concordances", {}).items()}},
    }
    out["axis"]["x_max"] = t2x(out["axis"]["to"], end=True)
    out["axis"]["fascicles"] = [[n, t, t2x(t)] for n, t in out["axis"].get("fascicles", [])]
    for s in out["sections"]:
        s.setdefault("x0", t2x(s["from"]))
        s.setdefault("x1", t2x(s["to"]))
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--sanskrit")
    ap.add_argument("--sanskrit-old-n1394u", help="old DSBC segmentation of SA_T06_n1394u that the alignments refer to")
    ap.add_argument("--matches", action="append", default=[], help="alignment release dir (oldest first)")
    ap.add_argument("--merge-only", action="store_true")
    args = ap.parse_args()

    dpath = os.path.join(DATA, "derived.json")
    if not args.merge_only:
        if not (args.sanskrit and args.matches):
            ap.error("--sanskrit and --matches are required unless --merge-only")
        derived = build_derived(args)
